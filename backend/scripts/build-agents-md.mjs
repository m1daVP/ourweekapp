import fs from 'node:fs/promises';
import path from 'node:path';

const rootDir = process.cwd();
const rulesDir = path.join(rootDir, 'agents');
const outputFile = path.join(rootDir, 'AGENTS.md');

const header = `# AGENTS.md

This file is generated from separate rule-set files in the \`agents/\` directory.

Do not edit this file directly.
Edit files inside \`agents/\` and run:

\`\`\`bash
npm run build:agents
\`\`\`

---

`;

const files = (await fs.readdir(rulesDir))
  .filter((file) => file.endsWith('.md'))
  .sort();

const sections = [];

for (const file of files) {
  const filePath = path.join(rulesDir, file);
  const content = await fs.readFile(filePath, 'utf8');

  sections.push(`<!-- Source: agents/${file} -->\n\n${content.trim()}\n`);
}

await fs.writeFile(outputFile, header + sections.join('\n---\n\n'), 'utf8');

console.log(`Generated AGENTS.md from ${files.length} rule files.`);
